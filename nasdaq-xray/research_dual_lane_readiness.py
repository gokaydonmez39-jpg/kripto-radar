#!/usr/bin/env python3
"""Research START / Verified AL START separation, observational and fail-closed.

Consumes SHA-bound witnesses generated by existing checkout-only workflows.
No provider calls, source promotion, broker use, candidate release or pointer writes.
"""
from __future__ import annotations
import argparse
import copy
import json
from pathlib import Path

SCHEMA = "XRAY_RESEARCH_VERIFIED_DUAL_LANE_READBACK_V1"
SAFE = {"execution": "NONE", "real_money": "NO-GO", "unknown_never_pass": True}
WATCH_CLASSES = {"DATA_BLOCKED", "TECH_FAIL", "WATCH_PRE_ENTRY", "WATCH_ENTRY_BAND", "WATCH_RETEST"}

def need(ok: bool, why: str) -> None:
    if not ok:
        raise ValueError("XRAY_DUAL_LANE_FAIL_CLOSED:" + why)

def inspect(start: dict, pre: dict) -> dict:
    need(isinstance(start, dict) and isinstance(pre, dict), "INPUT_TYPE")
    need(start.get("schema") == "XRAY_RESEARCH_MONITORING_START_WITNESS_V1", "START_SCHEMA")
    need(start.get("operational_status") == "RESEARCH_MONITORING_START_CONFIGURED", "START_NOT_CONFIGURED")
    need(pre.get("schema") == "XRAY_C417_PREENTRY_ATTRITION_WATCH_V1", "WATCH_SCHEMA")
    for name, source in (("START",start),("PREENTRY",pre)):
        need(all(source.get(k) is v if type(v) is bool else source.get(k)==v for k,v in SAFE.items()), name+"_SAFETY")
    need(start.get("alpha_go") is False and start.get("orders") == [] and start.get("buy_candidates") == [], "START_AUTHORITY")
    need(start.get("current_signal_release") == "NOT_ATTESTED" and start.get("primary_mc_attested") is False and start.get("delivery_receipt_attested") is False, "START_FALSE_PROMOTION")
    need(pre.get("alpha_authority") is False and pre.get("delivery_authority") is False, "PREENTRY_AUTHORITY")
    need(pre.get("r92_candidates") == pre.get("buy_candidates") == pre.get("orders") == [], "PREENTRY_FALSE_PROMOTION")
    need(pre.get("device_receipt_proven") is False and pre.get("github_delivery_recorded") is False, "PREENTRY_RECEIPT_CLAIM")
    start_refs=start.get("readback")
    pre_shas=pre.get("source_blobs")
    pre_asof=pre.get("source_asof")
    need(isinstance(start_refs,dict) and isinstance(pre_shas,dict) and isinstance(pre_asof,dict), "SOURCE_ENVELOPE")
    for key in ("terminal","master","price"):
        ref=start_refs.get(key)
        need(isinstance(ref,dict), "REFERENCE_"+key)
        sha=ref.get("blob_sha")
        need(isinstance(sha,str) and len(sha)==40 and all(c in "0123456789abcdef" for c in sha), "SHA_FORMAT_"+key)
        need(sha==pre_shas.get(key), "SOURCE_SHA_CHANGED_"+key)
        need(ref.get("asof_et")==pre_asof.get(key), "SOURCE_ASOF_CHANGED_"+key)
    counts=pre.get("disjoint_class_counts")
    n=pre.get("observed_final_count")
    nwatch=pre.get("prospective_watch_count")
    need(isinstance(counts,dict) and set(counts).issubset(WATCH_CLASSES) and all(type(v) is int and v>=0 for v in counts.values()), "CLASS_COUNTS")
    need(type(n) is int and n>=0 and sum(counts.values())==n, "DISJOINT_SUM")
    need(type(nwatch) is int and nwatch>=0, "WATCH_COUNT_TYPE")
    need(isinstance(pre.get("preentry_watch"),list) and isinstance(pre.get("prebreakout_b_armed_watch"),list), "WATCH_LIST_TYPE")
    need(nwatch==len(pre["preentry_watch"])+len(pre["prebreakout_b_armed_watch"]), "WATCH_COUNT_MISMATCH")
    need(type(start.get("input_epochs_aligned")) is bool and type(pre.get("source_exact")) is bool and type(pre.get("current_source_ready")) is bool, "BOOLEAN_READINESS")
    if pre["current_source_ready"]:
        need(pre["source_exact"] and start["input_epochs_aligned"] and not pre.get("source_binding_discrepancies"), "FALSE_CURRENT_READY")
        need(pre.get("status")=="PROSPECTIVE_RESEARCH_WATCH_ONLY", "WATCH_CURRENT_STATUS")
        need(pre.get("historical_diagnostic_only")==[], "LIVE_HISTORICAL_MIX")
    else:
        need(pre.get("status")=="DATA_BLOCKED_STALE_OR_INCOMPLETE_SOURCE", "WATCH_BLOCKED_STATUS")
        need(nwatch==0 and pre["preentry_watch"]==[] and pre["prebreakout_b_armed_watch"]==[], "STALE_LIVE_WATCH")
        need(counts.get("TECH_FAIL",0)==0, "TECH_FAIL_WITHOUT_CURRENT_SOURCES")
        need(counts.get("DATA_BLOCKED",0)==n, "STALE_NOT_DATA_BLOCKED")
    for observation in pre["preentry_watch"]+pre["prebreakout_b_armed_watch"]:
        need(isinstance(observation,dict) and observation.get("al") is False and observation.get("order") is False, "WATCH_MISLABELED_AL")
    ready=pre["current_source_ready"]
    research_state=("RESEARCH_WATCH_READY_NOT_AL" if nwatch else "RESEARCH_MONITORING_NO_CURRENT_WATCH") if ready else "RESEARCH_RUNNING_DATA_BLOCKED"
    return {
        "schema":SCHEMA,
        "research_start_status":research_state,
        "verified_al_start_status":"AWAIT_INDEPENDENT_CANONICAL_R92_RELEASE" if ready else "BLOCKED_CURRENT_SOURCE_CHAIN",
        "research_engine_configured":True,
        "current_source_chain_ready":ready,
        "source_epoch_alignment":start["input_epochs_aligned"],
        "source_exact":pre["source_exact"],
        "source_asof":{key:pre_asof.get(key) for key in ("terminal","master","price")},
        "readback_sha":{key:start_refs[key]["blob_sha"] for key in ("terminal","master","price")},
        "observed_final_count":n,
        "disjoint_class_counts":counts,
        "research_watch_count":nwatch,
        "independent_primary_mc_verified":False,
        "independent_r92_delivery_verified":False,
        "user_device_delivery_verified":False,
        "alpha_authority":False,"delivery_authority":False,
        "execution":"NONE","real_money":"NO-GO","unknown_never_pass":True,
        "r92_candidates":[],"buy_candidates":[],"orders":[],
        "notice":"Research-only observation; only Canonical can release independently proven current R92 candidates."
    }

def attach_manual_eod_observation(report: dict, manual: dict | None) -> dict:
    """Attach *human interactive* EOD research observations, never Canonical AL.

    The existing independent SIP provenance verifier must produce the input.
    Passing through an archive or a source mismatch yields zero current watches.
    """
    value=dict(report)
    value.update(manual_eod_watch_status="NOT_VERIFIED",
                 manual_eod_watch_count=0, manual_eod_watch_symbols=[],
                 manual_eod_not_automated=True,
                 manual_eod_alpha_authority=False,
                 manual_eod_r92_authority=False)
    if manual is None:
        return value
    need(isinstance(manual,dict) and manual.get("schema") ==
         "XRAY_MANUAL_SIP_WATCH_PROVENANCE_READBACK_V1","MANUAL_WITNESS_SCHEMA")
    need(manual.get("execution")=="NONE" and manual.get("real_money")=="NO-GO"
         and manual.get("unknown_never_pass") is True,"MANUAL_SAFETY")
    need(manual.get("not_a_buy_signal") is True
         and manual.get("full_go") is False
         and manual.get("r92_registered")==0
         and manual.get("candidate_delivery_performed") is False
         and manual.get("orders")==[]
         and manual.get("live_provider_replay_or_licensing_attested") is False,
         "MANUAL_FALSE_PROMOTION")
    need(manual.get("technical_C417_AL_count")=="UNVERIFIED",
         "MANUAL_AL_IS_UNVERIFIED_NOT_ZERO")
    require_status=manual.get("status")
    need(require_status in ("EOD_MANUAL_TECH_WATCH_CURRENT_UNREPLAYED",
                            "STALE_ARCHIVAL_SNAPSHOT_NOT_CURRENT"),"MANUAL_STATUS")
    current=(require_status=="EOD_MANUAL_TECH_WATCH_CURRENT_UNREPLAYED")
    symbols=manual.get("current_eod_research_watch")
    need(isinstance(symbols,list) and
         symbols==sorted(set(symbols)) and
         all(isinstance(x,str) and x and x.replace(".","").replace("-","").isalnum() for x in symbols),
         "MANUAL_WATCH_SET")
    need(manual.get("current_eod_research_watch_count")==len(symbols),
         "MANUAL_WATCH_COUNT")
    need(isinstance(manual.get("source_git_blob_shas"),dict),
         "MANUAL_SOURCE_REFS")
    source_ok=all(manual["source_git_blob_shas"].get(k)==report["readback_sha"].get(k)
                  for k in ("master","price"))
    same_asof=manual.get("snapshot_asof_et")==report["source_asof"].get("master") == report["source_asof"].get("price")
    completed=manual.get("latest_completed_session")==manual.get("snapshot_asof_et")
    if current:
        need(source_ok and same_asof and completed
             and manual.get("canonical_master_price_exact") is True
             and manual.get("same_asof_latest_completed") is True,
             "MANUAL_CURRENT_SOURCE_DRIFT")
        need(len(symbols)==11 and
             manual.get("observed_watch_count")==11 and
             manual.get("close_crosschecks")==11,
             "MANUAL_11_OBSERVATIONS")
        value.update(manual_eod_watch_status="CURRENT_COMPLETED_EOD_MANUAL_SHADOW_NOT_AL",
                     manual_eod_watch_count=len(symbols),
                     manual_eod_watch_symbols=symbols)
    else:
        need(not symbols and manual.get("current_eod_research_watch_count")==0,
             "STALE_MANUAL_WATCH_MUST_BE_EMPTY")
        value["manual_eod_watch_status"]="ARCHIVAL_ONLY_NO_CURRENT_MANUAL_WATCH"
    return value


def selftest() -> None:
    sha={k:c*40 for k,c in (("terminal","a"),("master","b"),("price","c"))}
    start={"schema":"XRAY_RESEARCH_MONITORING_START_WITNESS_V1","operational_status":"RESEARCH_MONITORING_START_CONFIGURED",**SAFE,"alpha_go":False,"orders":[],"buy_candidates":[],"current_signal_release":"NOT_ATTESTED","primary_mc_attested":False,"delivery_receipt_attested":False,"input_epochs_aligned":True,"readback":{k:{"asof_et":"2026-10-09","blob_sha":v} for k,v in sha.items()}}
    pre={"schema":"XRAY_C417_PREENTRY_ATTRITION_WATCH_V1",**SAFE,"alpha_authority":False,"delivery_authority":False,"r92_candidates":[],"buy_candidates":[],"orders":[],"device_receipt_proven":False,"github_delivery_recorded":False,"source_blobs":sha.copy(),"source_asof":{k:"2026-10-09" for k in sha},"source_exact":False,"current_source_ready":False,"source_binding_discrepancies":["MC_PRICE_BINDING_DRIFT"],"status":"DATA_BLOCKED_STALE_OR_INCOMPLETE_SOURCE","disjoint_class_counts":{"DATA_BLOCKED":17},"observed_final_count":17,"prospective_watch_count":0,"preentry_watch":[],"prebreakout_b_armed_watch":[],"historical_diagnostic_only":[]}
    r=inspect(start,pre)
    need(r["research_start_status"]=="RESEARCH_RUNNING_DATA_BLOCKED" and r["verified_al_start_status"]=="BLOCKED_CURRENT_SOURCE_CHAIN", "BASELINE")
    positive=copy.deepcopy(pre)
    positive.update(source_exact=True,current_source_ready=True,source_binding_discrepancies=[],status="PROSPECTIVE_RESEARCH_WATCH_ONLY",disjoint_class_counts={"WATCH_PRE_ENTRY":1},observed_final_count=1,prospective_watch_count=1,preentry_watch=[{"al":False,"order":False}])
    r=inspect(start,positive)
    need(r["research_start_status"]=="RESEARCH_WATCH_READY_NOT_AL" and r["alpha_authority"] is False and r["r92_candidates"]==[], "POSITIVE_WATCH_NOT_AL")
    invalids=[]
    for desc,k,value in (("sha","source_blobs",{**sha,"price":"d"*40}),("r92","r92_candidates",["TEST"]),("fake-tech","disjoint_class_counts",{"TECH_FAIL":17}),("stale-watch","prospective_watch_count",1),("false-ready","current_source_ready",True),("delivery","device_receipt_proven",True),("unknown","unknown_never_pass",False)):
        bad=copy.deepcopy(pre);bad[k]=value;invalids.append((desc,bad))
    for desc,bad in invalids:
        try: inspect(start,bad)
        except ValueError: pass
        else: raise RuntimeError("UNSAFE_CASE_ACCEPTED:"+desc)
    bad=copy.deepcopy(start);bad["readback"]["master"]["blob_sha"]="d"*40
    try:inspect(bad,pre)
    except ValueError:pass
    else:raise RuntimeError("START_PREIMAGE_DRIFT_ACCEPTED")
    manual={"schema":"XRAY_MANUAL_SIP_WATCH_PROVENANCE_READBACK_V1",
            **SAFE,"not_a_buy_signal":True,"full_go":False,
            "r92_registered":0,"candidate_delivery_performed":False,"orders":[],
            "live_provider_replay_or_licensing_attested":False,
            "technical_C417_AL_count":"UNVERIFIED",
            "status":"EOD_MANUAL_TECH_WATCH_CURRENT_UNREPLAYED",
            "current_eod_research_watch":["M%02d"%i for i in range(11)],
            "current_eod_research_watch_count":11,"observed_watch_count":11,
            "close_crosschecks":11,
            "source_git_blob_shas":sha.copy(),
            "snapshot_asof_et":"2026-10-09",
            "latest_completed_session":"2026-10-09",
            "canonical_master_price_exact":True,
            "same_asof_latest_completed":True}
    out=attach_manual_eod_observation(inspect(start,pre),manual)
    need(out["manual_eod_watch_count"]==11
         and out["verified_al_start_status"]=="BLOCKED_CURRENT_SOURCE_CHAIN"
         and out["r92_candidates"]==[],"MANUAL_WATCH_MUST_NOT_PROMOTE_AL")
    archived=copy.deepcopy(manual)
    archived.update(status="STALE_ARCHIVAL_SNAPSHOT_NOT_CURRENT",
                    current_eod_research_watch=[],current_eod_research_watch_count=0)
    need(attach_manual_eod_observation(inspect(start,pre),archived)["manual_eod_watch_count"]==0,
         "MANUAL_ARCHIVAL_GUARD")
    for field,value in (("r92_registered",1),("live_provider_replay_or_licensing_attested",True),
                        ("source_git_blob_shas",{**sha,"price":"d"*40}),
                        ("latest_completed_session","2026-10-08")):
        bad=copy.deepcopy(manual);bad[field]=value
        try:attach_manual_eod_observation(inspect(start,pre),bad)
        except ValueError:pass
        else:raise RuntimeError("MANUAL_FALSE_SOURCE_PROMOTION_ACCEPTED:"+field)
        print("XRAY_DUAL_LANE_SELFTEST=PASS_SOURCE_SHA_EPOCH_DISJOINT_NO_R92_NO_ORDER_NEGATIVES")

def main() -> None:
    p=argparse.ArgumentParser()
    p.add_argument("--selftest",action="store_true")
    p.add_argument("--start",type=Path)
    p.add_argument("--preentry",type=Path)
    p.add_argument("--manual",type=Path)
    p.add_argument("--out",type=Path)
    args=p.parse_args()
    if args.selftest:selftest();return
    if not args.start or not args.preentry or not args.out:p.error("--start, --preentry, --out required")
    value=inspect(json.loads(args.start.read_text()),json.loads(args.preentry.read_text()))
    value=attach_manual_eod_observation(value,json.loads(args.manual.read_text()) if args.manual else None)
    args.out.write_text(json.dumps(value,sort_keys=True,indent=2)+"\n")
    print("XRAY_RESEARCH_START="+value["research_start_status"])
    print("XRAY_VERIFIED_AL_START="+value["verified_al_start_status"])
    print("XRAY_MANUAL_EOD_WATCH="+value["manual_eod_watch_status"]+" count="+str(value["manual_eod_watch_count"]))
    print("XRAY_DUAL_LANE_BUY=0_EXECUTION_NONE")

if __name__=="__main__":main()
